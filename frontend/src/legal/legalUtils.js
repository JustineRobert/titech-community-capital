/* ============================================================================
 * Search helpers
 * ========================================================================== */

/**
 * Search registry metadata.
 *
 * This searches metadata only.
 * It does NOT search substantive legal content.
 */
export function searchLegalDocuments(
  searchTerm
) {
  if (!isNonEmptyString(searchTerm)) {
    return [];
  }

  const query =
    searchTerm.trim().toLowerCase();

  return LEGAL_DOCUMENTS.filter(
    (document) => {
      const searchableFields = [
        document.id,
        document.slug,
        document.title,
        document.shortTitle,
        document.category,
        document.priority,
        document.jurisdiction,
        ...normalizeArray(
          document.tags
        ),
        ...normalizeArray(
          document.audience
        ),
      ];

      return searchableFields.some(
        (field) =>
          String(field)
            .toLowerCase()
            .includes(query)
      );
    }
  );
}

/* ============================================================================
 * Date formatting
 * ========================================================================== */

/**
 * Format a legal date for user-facing display.
 *
 * Returns an empty string for invalid/missing dates.
 */
export function formatLegalDate(
  date,
  locale = DEFAULT_LOCALE
) {
  const parsed =
    parseLegalDate(date);

  if (!parsed) {
    return '';
  }

  try {
    return new Intl.DateTimeFormat(
      locale,
      VALID_DATE_FORMAT_OPTIONS
    ).format(parsed);
  } catch {
    return new Intl.DateTimeFormat(
      DEFAULT_LOCALE,
      VALID_DATE_FORMAT_OPTIONS
    ).format(parsed);
  }
}

/**
 * Format a document's effective date.
 */
export function formatEffectiveDate(
  document,
  locale = DEFAULT_LOCALE
) {
  return formatLegalDate(
    document?.effectiveDate,
    locale
  );
}

