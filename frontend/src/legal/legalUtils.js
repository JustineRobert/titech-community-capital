/* ============================================================================
 * Registry statistics
 * ========================================================================== */

/**
 * Produce lightweight registry statistics.
 *
 * Useful for:
 *   - administration
 *   - development diagnostics
 *   - automated tests
 *   - observability
 */
export function getLegalRegistryStatistics() {
  const documents =
    LEGAL_DOCUMENTS;

  return Object.freeze({
    total: documents.length,

    published:
      documents.filter(
        (document) =>
          document.status ===
          LEGAL_STATUS.PUBLISHED
      ).length,

    public:
      documents.filter(
        (document) =>
          document.public === true
      ).length,

    acceptanceRequired:
      documents.filter(
        (document) =>
          document.requiresAcceptance === true
      ).length,

    critical:
      documents.filter(
        (document) =>
          document.priority ===
          LEGAL_PRIORITY.CRITICAL
      ).length,

    drafts:
      documents.filter(
        (document) =>
          document.status ===
          LEGAL_STATUS.DRAFT
      ).length,

    review:
      documents.filter(
        (document) =>
          document.status ===
          LEGAL_STATUS.REVIEW
      ).length,

    scheduled:
      documents.filter(
        (document) =>
          document.status ===
          LEGAL_STATUS.SCHEDULED
      ).length,

    superseded:
      documents.filter(
        (document) =>
          document.status ===
          LEGAL_STATUS.SUPERSEDED
      ).length,

    retired:
      documents.filter(
        (document) =>
          document.status ===
          LEGAL_STATUS.RETIRED
      ).length,
  });
}

/* ============================================================================
 * Development diagnostics
 * ========================================================================== */

/**
 * Log registry diagnostics without exposing legal content.
 *
 * Never log:
 *   - acceptance records
 *   - personal data
 *   - document contents
 *   - authentication data
 *   - secrets
 */
export function logLegalRegistryDiagnostics(
  logger = console
) {
  const validation =
    validateLegalConfiguration();

  const statistics =
    getLegalRegistryStatistics();

  if (
    validation.valid
  ) {
    logger.info(
      '[TITech Legal] Registry validation passed.',
      statistics
    );
  } else {
    logger.error(
      '[TITech Legal] Registry validation failed.',
      validation.errors
    );
  }

  return Object.freeze({
    validation,
    statistics,
  });
}

