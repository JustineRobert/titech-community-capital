/* ============================================================================
 * Legal document status helpers
 * ========================================================================== */

/**
 * Return a normalized status label.
 */
export function getLegalStatusLabel(
  document
) {
  const status =
    document?.status;

  if (!status) {
    return '';
  }

  return String(status)
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, (letter) =>
      letter.toUpperCase()
    );
}

