/* ============================================================================
 * Effective-date helpers
 * ========================================================================== */

/**
 * Determine whether a document has a valid effective date.
 */
export function isEffectiveDocument(
  document,
  referenceDate = new Date()
) {
  if (!document?.effectiveDate) {
    return false;
  }

  const effectiveDate =
    parseLegalDate(
      document.effectiveDate
    );

  if (!effectiveDate) {
    return false;
  }

  const reference =
    parseLegalDate(referenceDate);

  if (!reference) {
    return false;
  }

  return effectiveDate.getTime() <=
    reference.getTime();
}

/**
 * Determine whether a document is scheduled for a future effective date.
 */
export function isFutureEffectiveDocument(
  document,
  referenceDate = new Date()
) {
  if (!document?.effectiveDate) {
    return false;
  }

  const effectiveDate =
    parseLegalDate(
      document.effectiveDate
    );

  const reference =
    parseLegalDate(referenceDate);

  if (!effectiveDate || !reference) {
    return false;
  }

  return effectiveDate.getTime() >
    reference.getTime();
}

