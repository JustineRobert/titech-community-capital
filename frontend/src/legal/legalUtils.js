/**
 * Determine whether a legal document is currently published.
 *
 * A document is considered published only when:
 *   - status === published
 *   - an effective date exists
 */
export function isPublishedDocument(document) {
  return Boolean(
    document &&
    document.status === LEGAL_STATUS.PUBLISHED &&
    isEffectiveDocument(document)
  );
}

/**
 * Determine whether a document is publicly accessible according to its
 * registry metadata and lifecycle.
 */
export function isPublicDocument(document) {
  return Boolean(
    document &&
    document.public === true &&
    [
      LEGAL_STATUS.APPROVED,
      LEGAL_STATUS.SCHEDULED,
      LEGAL_STATUS.PUBLISHED,
    ].includes(document.status)
  );
}

