/**
 * Validate the complete legal configuration.
 *
 * This should be called during:
 *   - development startup
 *   - automated tests
 *   - CI/CD validation
 *   - pre-production verification
 *
 * The authoritative validation rules live in legalTypes.js.
 */
export function validateLegalConfiguration() {
  return validateLegalRegistry(
    LEGAL_DOCUMENTS
  );
}

/**
 * Validate a single legal document.
 */
export function validateLegalDocument(document) {
  if (!document) {
    return {
      valid: false,
      errors: ['Legal document is required.'],
    };
  }

  try {
    const result = validateLegalRegistry([document]);

    return result;
  } catch (error) {
    return {
      valid: false,
      errors: [
        error?.message ||
          'Unable to validate legal document.',
      ],
    };
  }
}

/* ============================================================================
 * Document normalization
 * ========================================================================== */

/**
 * Normalize a legal document through the canonical legalTypes layer.
 *
 * Falls back to the original document if normalizeLegalDocument is not
 * available in an older legalTypes implementation.
 */
export function normalizeLegalDocumentMetadata(document) {
  if (!document) {
    return null;
  }

  if (typeof normalizeLegalDocument === 'function') {
    return normalizeLegalDocument(document);
  }

  return document;
}

/**
 * Normalize a legal-document version.
 *
 * Examples:
 *   " 1.0.0 " -> "1.0.0"
 *   null       -> null
 *   ""         -> null
 */
export function normalizeLegalVersion(version) {
  if (
    version === null ||
    version === undefined
  ) {
    return null;
  }

  const normalized = String(version).trim();

  return normalized || null;
}

/**
 * Extract the current version from a legal document.
 */
export function getLegalDocumentVersion(document) {
  if (!document) {
    return null;
  }

  return normalizeLegalVersion(
    document.currentVersion
  );
}

/* ============================================================================
 * Document lookup
 * ========================================================================== */

/**
 * Find a legal document by immutable document ID.
 */
export function findLegalDocumentById(id) {
  if (!isNonEmptyString(id)) {
    return null;
  }

  return getLegalDocumentById(id.trim());
}

/**
 * Find a legal document by public slug.
 */
export function findLegalDocumentBySlug(slug) {
  if (!isNonEmptyString(slug)) {
    return null;
  }

  return getLegalDocumentBySlug(slug.trim());
}

/**
 * Resolve a document using either its ID or slug.
 */
export function resolveLegalDocument(identifier) {
  if (!isNonEmptyString(identifier)) {
    return null;
  }

  const normalizedIdentifier =
    identifier.trim();

  return (
    findLegalDocumentById(
      normalizedIdentifier
    ) ||
    findLegalDocumentBySlug(
      normalizedIdentifier
    )
  );
}

