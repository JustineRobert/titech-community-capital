  async function (
    reason
  ) {
    this.recoveryRequired =
      true;

    this.recoveryCount =
      Number(this.recoveryCount || 0) + 1;

    this.recoveryReason =
      reason
        ? String(reason).slice(0, 500)
        : "Transaction requires recovery.";

    return this.save();
  };

