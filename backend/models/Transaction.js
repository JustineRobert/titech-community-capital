/**
 * ============================================================================
 * ATOMIC IDEMPOTENT CREATE
 * ============================================================================
 *
 * This helper intentionally uses the database unique indexes as the final
 * concurrency guard.
 *
 * The service should:
 *
 * 1. Try to find the existing transaction.
 * 2. Attempt creation.
 * 3. Handle E11000 by retrieving the existing transaction.
 *
 * Never rely on "find then create" alone for financial idempotency.
 * ============================================================================
 */

transactionSchema.statics.createIdempotent =
  async function (
    payload
  ) {
    try {
      return await this.create(
        payload
      );
    } catch (error) {
      if (
        error &&
        error.code === 11000
      ) {
        const tenantId =
          payload.tenantId;

        const idempotencyKey =
          payload.idempotencyKey;

        if (
          tenantId &&
          idempotencyKey
        ) {
          const existing =
            await this.findOne({
              tenantId,
              idempotencyKey,
              deletedAt: null,
            });

          if (existing) {
            return existing;
          }
        }

        if (
          payload.externalId
        ) {
          const existing =
            await this.findOne({
              tenantId,
              externalId:
                payload.externalId,
              deletedAt: null,
            });

          if (existing) {
            return existing;
          }
        }
      }

      throw error;
    }
  };

