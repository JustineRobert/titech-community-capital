/**
 * ============================================================================
 * ATOMIC PROCESSING CLAIM
 * ============================================================================
 *
 * This method is useful for transaction workers.
 *
 * Only a transaction currently in a claimable state can be moved to
 * PROCESSING.
 *
 * Multiple workers attempting to claim the same transaction will not all
 * receive the transaction.
 * ============================================================================
 */

transactionSchema.statics.claimForProcessing =
  async function (
    transactionId,
    tenantId,
    options = {}
  ) {
    const now =
      new Date();

    const leaseMinutes =
      Math.max(
        1,
        Number(
          options.leaseMinutes || 15
        )
      );

    const leaseExpiresAt =
      new Date(
        now.getTime() +
        leaseMinutes * 60 * 1000
      );

    const query = {
      _id: transactionId,
      status: {
        $in: [
          "PENDING",
          "FAILED",
          "EXPIRED",
        ],
      },
      deletedAt: null,
    };

    if (tenantId) {
      query.tenantId =
        tenantId;
    }

    return this.findOneAndUpdate(
      query,
      {
        $set: {
          status: "PROCESSING",

          processingStartedAt:
            now,

          processingLeaseExpiresAt:
            leaseExpiresAt,

          lastAttemptAt:
            now,

          workerId:
            options.workerId || null,

          updatedBy:
            options.updatedBy || null,
        },

        $inc: {
          attempts: 1,
        },
      },
      {
        new: true,
        runValidators: true,
      }
    );
  };

